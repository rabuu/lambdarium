use miette::{Diagnostic, SourceOffset, SourceSpan};
use thiserror::Error;

use crate::lowering::LoweringError;
use crate::parser::lexer::{LexerError, Token};

#[derive(Error, Diagnostic, Debug)]
pub enum ParserError {
    #[error("Encountered invalid token.")]
    InvalidToken {
        #[label]
        span: Option<SourceSpan>,
    },

    #[error("Unexpected end of input, expected one of: {expected}")]
    UnexpectedEof {
        #[label]
        location: SourceOffset,
        expected: String,
    },

    #[error("Unexpected {token}, expected one of: {expected}")]
    UnexpectedToken {
        #[label]
        span: SourceSpan,
        token: String,
        expected: String,
    },

    #[error("Unexpected {token}.")]
    UnexpectedExtraToken {
        #[label]
        span: SourceSpan,
        token: String,
    },

    #[error("This is not a valid core λ-term.")]
    #[diagnostic(help("This is a valid term in our meta language. You can parse it as such."))]
    InvalidCoreTerm(#[from] LoweringError),
}

impl From<lalrpop_util::ParseError<usize, Token, LexerError>> for ParserError {
    fn from(value: lalrpop_util::ParseError<usize, Token, LexerError>) -> Self {
        match value {
            lalrpop_util::ParseError::InvalidToken { .. } => unreachable!(
                "This error can only be generated by the internal LALRPOP lexer which we don't use."
            ),
            lalrpop_util::ParseError::UnrecognizedEof { location, expected } => {
                ParserError::UnexpectedEof {
                    location: location.into(),
                    expected: expected.join(", "),
                }
            }
            lalrpop_util::ParseError::UnrecognizedToken { token, expected } => {
                ParserError::UnexpectedToken {
                    span: token.span(),
                    token: token.string(),
                    expected: expected.join(", "),
                }
            }
            lalrpop_util::ParseError::ExtraToken { token } => ParserError::UnexpectedExtraToken {
                span: token.span(),
                token: token.string(),
            },
            lalrpop_util::ParseError::User { error } => match error {
                LexerError::InvalidToken => ParserError::InvalidToken { span: None },
            },
        }
    }
}

trait ToMietteExt {
    fn string(&self) -> String;
    fn span(&self) -> SourceSpan;
}

impl ToMietteExt for (usize, Token, usize) {
    fn span(&self) -> SourceSpan {
        (self.0, self.2 - self.0).into()
    }

    fn string(&self) -> String {
        self.1.to_string()
    }
}
